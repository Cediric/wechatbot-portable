# 加载自定义映射（可选）
_custom_map = {}
if config.FACE_MAPPING_FILE and os.path.isfile(config.FACE_MAPPING_FILE):
    try:
        with open(config.FACE_MAPPING_FILE, "r", encoding="utf-8") as f:
            data = json.load(f)
        if isinstance(data, dict):
            _custom_map = {str(k): v for k, v in data.items()}
            log.info(f"[sticker] 已加载自定义 face 映射: {config.FACE_MAPPING_FILE}")
    except Exception as e:
        log.warning(f"[sticker] 加载自定义 face 映射失败: {e}")


def resolve_face(face_id) -> str:
    """把 OneBot face id 转为微信表情文本；未知返回 '[表情]'。"""
    if face_id is None:
        return "[表情]"
    key = str(face_id)
    if key in _custom_map:
        return _custom_map[key]
    return FACE_ID_TO_WECHAT.get(face_id, FACE_ID_TO_WECHAT.get(int(face_id) if str(face_id).isdigit() else -1, "[表情]"))

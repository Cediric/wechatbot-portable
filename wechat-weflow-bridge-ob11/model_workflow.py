def workflow_prompt(profile):
    return _COMMON + "\n\n[本模型在工作流中的职责]\n" + _ROLES[profile]


def with_workflow_prompt(profile, prompt):
    fixed = workflow_prompt(profile)
    text = str(prompt or "").strip()
    return text if text.endswith(fixed) else text + ("\n\n" if text else "") + fixed
